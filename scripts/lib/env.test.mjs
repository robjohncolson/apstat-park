test('shared secret: compares the EFFECTIVE value (FRQ_GRADER_SECRET overrides) and names each side', () => {
  const relay = goodRelay();
  const rosterFile = { ROSTER_GRADER_SECRET: relay.ROSTER_GRADER_SECRET, FRQ_GRADER_SECRET: 'z'.repeat(64) };

  // relay side: roster's effective secret is FRQ_GRADER_SECRET, which differs
  const fromRelay = validateEnv({ schema, identity, svc: 'relay', env: relay, fileEnv: relay, otherFileEnvs: { roster: rosterFile } });
  assert.equal(status(fromRelay, 'ROSTER_GRADER_SECRET'), 'FAIL');
  assert.match(note(fromRelay, 'ROSTER_GRADER_SECRET'), /must equal roster's FRQ_GRADER_SECRET/);
  assert.match(note(fromRelay, 'ROSTER_GRADER_SECRET'), /this side: ROSTER_GRADER_SECRET from relay's \.env/);

  // roster side: the override row warns that it differs from the base key, the base row compares the override
  const fromRoster = validateEnv({ schema, identity, svc: 'roster', env: rosterFile, fileEnv: rosterFile, otherFileEnvs: { relay } });
  assert.equal(status(fromRoster, 'FRQ_GRADER_SECRET'), 'WARN');
  assert.equal(status(fromRoster, 'ROSTER_GRADER_SECRET'), 'FAIL');
  assert.match(note(fromRoster, 'ROSTER_GRADER_SECRET'), /overridden by FRQ_GRADER_SECRET/);

  // live environment beats the file, and the message says so
  const fileEnv = { ...relay, ROSTER_GRADER_SECRET: 'file-value' };
  const live = validateEnv({ schema, identity, svc: 'relay', env: { ...fileEnv, ROSTER_GRADER_SECRET: rosterFile.FRQ_GRADER_SECRET }, fileEnv, otherFileEnvs: { roster: rosterFile } });
  assert.equal(status(live, 'ROSTER_GRADER_SECRET'), 'PASS');
  assert.match(note(live, 'ROSTER_GRADER_SECRET'), /ROSTER_GRADER_SECRET from live environment = FRQ_GRADER_SECRET from roster's \.env/);
});
