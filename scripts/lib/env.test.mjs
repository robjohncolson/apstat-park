import test from 'node:test';
import assert from 'node:assert/strict';
import { REPO_ROOT } from './args.mjs';
import { loadSchema, loadIdentity, parseEnv, serializeValue, renderExample, renderEnvFile, validateEnv, mask } from './env.mjs';

const schema = loadSchema(REPO_ROOT);
const identity = loadIdentity(REPO_ROOT);
const cur = identity.current;

// A complete, valid relay env built from the schema.
function goodRelay() {
  return {
    SUPABASE_URL: cur.supabase_url,
    SUPABASE_ANON_KEY: cur.supabase_anon_key,
    SUPABASE_SERVICE_KEY: 'service-key-xyz',
    ROSTER_TOKEN_SECRET: 'a'.repeat(64),
    ROSTER_GRADER_SECRET: 'b'.repeat(64),
    PARK_KEY_GRANT_SECRET: 'c'.repeat(64),
    RECEIPT_ISSUER_PRIVATE_KEY: 'MC4CAQAwBQYDK2VwBCIEI',
    GROQ_API_KEY: 'gsk_test',
    ROSTER_SERVICE_URL: cur.roster_url,
    CURRICULUM_URL: `${cur.quiz_base}/data/curriculum.js`,
    AI_GRADE_AUTH: 'log',
    TEACHER_SECRET: 'otter-maple-river-sage-12'
  };
}
const status = (res, key) => res.rows.find((r) => r.key === key)?.status;

test('parseEnv / serializeValue round-trip quoting', () => {
  const values = { A: 'plain', B: 'Period B;Period E', C: 'has "quote" and \\ slash', D: 'x=y+z/w', E: '' };
  const text = Object.entries(values).map(([k, v]) => `${k}=${serializeValue(v)}`).join('\n');
  assert.deepEqual(parseEnv(`# comment\n${text}\nexport F=1 # trailing\n`), { ...values, F: '1' });
});

test('renderExample: sections, docs, secrets, shared, identity prefill, defaults', () => {
  const roster = renderExample(schema, identity, 'roster');
  const relay = renderExample(schema, identity, 'relay');
  for (const t of ['Required', 'Recommended', 'Optional', 'Feature flags', 'Platform']) assert.match(roster, new RegExp(`# =+ ${t}`));
  assert.match(roster, /# HMAC secret for student session tokens/);
  assert.match(roster, /# secret; generated by setup\.mjs \(hex32\); must equal relay ROSTER_TOKEN_SECRET\nROSTER_TOKEN_SECRET=\n/);
  assert.match(roster, new RegExp(`\\nROSTER_SUPABASE_URL=${cur.supabase_url.replace(/\./g, '\\.')}\\n`));
  assert.match(roster, /\nUSE_V3_GRADING=true\n/);
  assert.match(roster, /\nOPEN_SIGNUP_SECTIONS="PeriodB:Period B;PeriodE:Period E"\n/);
  assert.match(roster, /\n# PORT=\n/);
  assert.match(relay, /at least one of GROQ_API_KEY \/ DEEPSEEK_API_KEY/);
  assert.match(relay, new RegExp(`\\nCURRICULUM_URL=${cur.quiz_base.replace(/[./]/g, '\\$&')}/data/curriculum\\.js\\n`));
  assert.doesNotMatch(relay, /TEACHER_SECRET=\S/); // secrets never pre-filled
});

test('validateEnv: complete relay env passes', () => {
  const res = validateEnv({ schema, identity, svc: 'relay', env: goodRelay() });
  assert.equal(res.ok, true, JSON.stringify(res.rows.filter((r) => r.status === 'FAIL')));
});

test('validateEnv: missing required key fails', () => {
  const env = goodRelay();
  delete env.SUPABASE_SERVICE_KEY;
  const res = validateEnv({ schema, identity, svc: 'relay', env });
  assert.equal(res.ok, false);
  assert.equal(status(res, 'SUPABASE_SERVICE_KEY'), 'FAIL');
});

test('validateEnv: one_of satisfied by either member, fails when neither', () => {
  const env = goodRelay();
  delete env.GROQ_API_KEY;
  env.DEEPSEEK_API_KEY = 'sk-deep';
  let res = validateEnv({ schema, identity, svc: 'relay', env });
  assert.equal(res.ok, true);
  assert.equal(status(res, 'GROQ_API_KEY'), 'UNSET');
  delete env.DEEPSEEK_API_KEY;
  res = validateEnv({ schema, identity, svc: 'relay', env });
  assert.equal(res.ok, false);
  assert.equal(status(res, 'GROQ_API_KEY'), 'FAIL');
  assert.equal(status(res, 'DEEPSEEK_API_KEY'), 'FAIL');
});

test('validateEnv: shared_with mismatch fails, match passes, missing other file is not compared', () => {
  const env = goodRelay();
  const roster = { ROSTER_TOKEN_SECRET: 'a'.repeat(64), ROSTER_GRADER_SECRET: 'DIFFERENT', PARK_KEY_GRANT_SECRET: 'c'.repeat(64) };
  const res = validateEnv({ schema, identity, svc: 'relay', env, fileEnv: env, otherFileEnvs: { roster } });
  assert.equal(res.ok, false);
  assert.equal(status(res, 'ROSTER_GRADER_SECRET'), 'FAIL');
  assert.equal(status(res, 'ROSTER_TOKEN_SECRET'), 'PASS');
  const alone = validateEnv({ schema, identity, svc: 'relay', env, fileEnv: env, otherFileEnvs: { roster: null } });
  assert.equal(alone.ok, true);
});

test('validateEnv: from_identity drift warns; test_only keys warn outside test', () => {
  const env = { ...goodRelay(), ROSTER_SERVICE_URL: 'https://old.example' };
  const res = validateEnv({ schema, identity, svc: 'relay', env });
  assert.equal(status(res, 'ROSTER_SERVICE_URL'), 'WARN');
  assert.equal(res.ok, true);
  const r2 = validateEnv({ schema, identity, svc: 'roster', env: { GRADE_FREEZE_DIR: '/tmp/x', NODE_ENV: 'production' } });
  assert.equal(status(r2, 'GRADE_FREEZE_DIR'), 'WARN');
  const r3 = validateEnv({ schema, identity, svc: 'roster', env: { GRADE_FREEZE_DIR: '/tmp/x', NODE_ENV: 'test' } });
  assert.equal(status(r3, 'GRADE_FREEZE_DIR'), 'INFO');
});

test('secrets are masked in rows (first 4 chars + length)', () => {
  const env = goodRelay();
  const res = validateEnv({ schema, identity, svc: 'relay', env });
  const row = res.rows.find((r) => r.key === 'SUPABASE_SERVICE_KEY');
  assert.equal(row.shown, mask(env.SUPABASE_SERVICE_KEY));
  assert.equal(row.shown, 'serv...(15)');
  for (const r of res.rows) assert.ok(!String(r.shown).includes('a'.repeat(64)));
});

test('renderEnvFile keeps unknown keys and parses back', () => {
  const text = renderEnvFile(schema, 'relay', { ...goodRelay(), CUSTOM_THING: 'keep me' });
  const back = parseEnv(text);
  assert.equal(back.CUSTOM_THING, 'keep me');
  assert.equal(back.SUPABASE_URL, cur.supabase_url);
});
